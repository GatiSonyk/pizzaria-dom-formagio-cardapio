-- Dom Formagio catalog + role-based admin schema
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'usuario' check (role in ('administrador','equipe','usuario')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.current_user_role()
returns text
language sql stable security definer
set search_path = public
as $$
  select p.role from public.profiles p where p.id = auth.uid() limit 1
$$;

create or replace function public.is_catalog_admin()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select coalesce(public.current_user_role() = 'administrador', false)
$$;

create or replace function public.can_manage_catalog()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select coalesce(public.current_user_role() in ('administrador','equipe'), false)
$$;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql security definer
set search_path = public, auth
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(nullif(new.raw_user_meta_data->>'full_name',''), split_part(coalesce(new.email,''),'@',1)),
    'usuario'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_dom_formagio on auth.users;
create trigger on_auth_user_created_dom_formagio
  after insert on auth.users
  for each row execute procedure public.handle_new_auth_user();

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  category text not null check (category in ('Tradicionais','Especiais','Doces','Bebidas')),
  description text not null default '',
  image_url text,
  price_large numeric(10,2) check (price_large is null or price_large >= 0),
  price_medium numeric(10,2) check (price_medium is null or price_medium >= 0),
  price_small numeric(10,2) check (price_small is null or price_small >= 0),
  price_unit numeric(10,2) check (price_unit is null or price_unit >= 0),
  is_available boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_sort_idx on public.products(category, sort_order);
create index if not exists products_available_idx on public.products(is_available);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at before update on public.products
for each row execute procedure public.set_updated_at();

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
for each row execute procedure public.set_updated_at();

create table if not exists public.catalog_settings (
  id integer primary key default 1 check (id = 1),
  border_addon_price numeric(10,2) not null default 18.00 check (border_addon_price >= 0),
  updated_at timestamptz not null default now()
);
insert into public.catalog_settings (id, border_addon_price) values (1,18.00)
on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.catalog_settings enable row level security;

grant select on public.profiles to authenticated;
grant update (full_name) on public.profiles to authenticated;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant select on public.catalog_settings to anon, authenticated;
grant update on public.catalog_settings to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

drop policy if exists "profiles_read_self_or_admin" on public.profiles;
create policy "profiles_read_self_or_admin" on public.profiles
for select to authenticated
using (id = auth.uid() or public.is_catalog_admin());

drop policy if exists "profiles_update_self_name" on public.profiles;
create policy "profiles_update_self_name" on public.profiles
for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

drop policy if exists "products_read_public_available" on public.products;
create policy "products_read_public_available" on public.products
for select to anon, authenticated
using (is_available = true or public.can_manage_catalog());

drop policy if exists "products_insert_catalog_managers" on public.products;
create policy "products_insert_catalog_managers" on public.products
for insert to authenticated
with check (public.can_manage_catalog());

drop policy if exists "products_update_catalog_managers" on public.products;
create policy "products_update_catalog_managers" on public.products
for update to authenticated
using (public.can_manage_catalog())
with check (public.can_manage_catalog());

drop policy if exists "products_delete_catalog_managers" on public.products;
create policy "products_delete_catalog_managers" on public.products
for delete to authenticated
using (public.can_manage_catalog());

drop policy if exists "catalog_settings_read_all" on public.catalog_settings;
create policy "catalog_settings_read_all" on public.catalog_settings
for select to anon, authenticated using (true);

drop policy if exists "catalog_settings_update_admin" on public.catalog_settings;
create policy "catalog_settings_update_admin" on public.catalog_settings
for update to authenticated
using (public.is_catalog_admin())
with check (public.is_catalog_admin());

